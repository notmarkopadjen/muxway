def png(path, rows, scale):
    h = len(rows)
    w = len(rows[0])
    raw = bytearray()
    for y in range(h * scale):
        raw.append(0)
        for x in range(w * scale):
            c = rows[y // scale][x // scale]
            raw += bytes({"#": AMBER, "+": DIM}.get(c, BLACK))
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    out = b"\x89PNG\r\n\x1a\n"
    out += chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 2, 0, 0, 0))
    out += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    out += chunk(b"IEND", b"")
    path.write_bytes(out)


def main():
    here = Path(__file__).parent
    for name, art in GLYPHS.items():
        rows = [r for r in art.strip("\n").split("\n")]
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), name
        # a dim one-pixel frame around the glyph
        framed = ["+" * 18] + ["+" + r + "+" for r in rows] + ["+" * 18]
        png(here / f"{name}.png", framed, SCALE)
        print(name)


if __name__ == "__main__":
    main()
